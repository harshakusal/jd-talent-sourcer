// Bundles web/main.ts (+ shared src/ logic) into docs/app.js. Run: npm run build:web
import { build } from 'esbuild';
import { readFileSync } from 'fs';
const sample = readFileSync(new URL('../samples/sample_jd.txt', import.meta.url), 'utf8');
await build({
  entryPoints: ['web/main.ts'], bundle: true, minify: true, format: 'iife', target: 'es2020',
  outfile: 'docs/app.js', alias: { '@nestjs/common': './web/nest-shim.ts' },
  banner: { js: '/* jd-talent-sourcer browser build — generated by web/build.mjs; edit src/ or web/ instead */\nvar process = globalThis.process || { env: {} };' },
  define: { SAMPLE_JD: JSON.stringify(sample) }, legalComments: 'none',
});
console.log('built docs/app.js');
